#!/usr/bin/env node
/*
 * Regenerates the public front-end bundle:
 *   ../tzfdform-public.js          minified (shipped, enqueued by the plugin)
 *   tzfdform-public.src.js         readable copy of the same code (formatted, not minified)
 *
 * The readable code is the output of ../tzfdform-loader-public.php, which concatenates
 * jQuery.stringify.js, jquery.validate.js, tzfd-public-accessibility.js, tzfd-calendar.js,
 * tzfdform-core-public.jquery.js and every file in tzfdform-public-fields/ (sorted by name).
 * The PHP loader runs in the php CLI with ABSPATH defined so that it needs no WordPress.
 *
 * Usage (from js/src):  npm ci && node build-tzfdform-public.js
 */
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const prettier = require('prettier');
const { minify } = require('terser');

const JS_DIR = path.resolve(__dirname, '..');
const BANNER =
	'/*! Titan Zero Trades: Front Desk public form bundle. Generated from js/src/tzfdform-public.src.js ' +
	'by js/src/build-tzfdform-public.js. See js/src/README.md. */\n';

async function main() {
	// 1. Concatenate the sources exactly as the PHP loader does.
	const raw = execFileSync('php', ['-r', 'define("ABSPATH", "/"); require "tzfdform-loader-public.php";'], {
		cwd: JS_DIR,
		encoding: 'utf8',
		maxBuffer: 64 * 1024 * 1024,
	});

	// 2. Readable copy (formatting only, behaviour unchanged).
	const readable = await prettier.format(raw, { parser: 'babel' });
	const srcFile = path.join(__dirname, 'tzfdform-public.src.js');
	fs.writeFileSync(srcFile, '// Readable source for ../tzfdform-public.js. Generated by build-tzfdform-public.js. Do not edit.\n' + readable);

	// 3. Minify the readable copy.
	const result = await minify(readable, {
		compress: true,
		mangle: true,
		format: { comments: /^!/ },
	});
	if (result.error) throw result.error;
	fs.writeFileSync(path.join(JS_DIR, 'tzfdform-public.js'), BANNER + result.code + '\n');

	console.log('wrote', path.relative(process.cwd(), srcFile), 'and js/tzfdform-public.js');
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
